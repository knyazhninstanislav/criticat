"""
Тексты фраз для озвучки.
"""

PHRASES = {
    'critical_department': (
        "Внимание. В вашем отделении найден критический результат "
        "лабораторного исследования. Срочно свяжитесь с дежурным врачом. "
        "Повторяю: критический результат. Срочно свяжитесь с дежурным врачом."
    ),

    'critical_reanimation': (
        "Внимание. Критический результат в реанимационном отделении. "
        "Срочно свяжитесь с дежурным врачом. "
        "Повторяю: критический результат. Срочно свяжитесь с дежурным врачом."
    ),

    'escalation_head': (
        "Внимание. Критический результат не был подтверждён дежурным врачом "
        "в течение пятнадцати минут. Требуется ваше вмешательство. "
        "Срочно свяжитесь с дежурным врачом."
    ),

    'escalation_chief': (
        "Внимание. Критический результат не был подтверждён в течение "
        "тридцати минут. Требуется немедленное вмешательство. "
        "Срочно свяжитесь с дежурным врачом."
    ),
}


def get_phrase(key: str, **kwargs) -> str:
    """Получить текст фразы по ключу с подстановкой плейсхолдеров."""
    template = PHRASES.get(key)
    if not template:
        template = PHRASES['critical_department']

    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template